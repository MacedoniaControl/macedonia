-- ============================================================================
-- 22 · DEPARTAMENTOS DE VALERY
--
-- En Valery cada producto pertenece a un Departamento (06 - HERRAMIENTAS
-- MANUALES, 05 - SOLDADURA...). Es la clasificacion con la que Sumigases
-- trabaja: se cuenta el inventario por departamento y Valery toma de el el %
-- de utilidad por defecto. Macedonia no la tenia.
--
-- Fuente: "Listado de Productos.xls" de Sumigases, exportado el 23-09-2026.
-- 26 departamentos y 2.207 productos. BRAGA queda sin departamento: en
-- Valery ni siquiera tiene nombre.
--
-- Correr DESPUES de 21-cuentas-historial.sql. Se puede correr mas de una vez.
-- Todo va con "public." porque el SQL Editor no siempre lo busca solo.
-- ============================================================================

create table if not exists public.departamentos (
  empresa_id text not null references public.empresas(id),
  -- El codigo de Valery ("06"), no un numero propio: es el que la gente ve en
  -- los reportes y el que hay que usar para cruzar con el proximo listado.
  codigo     text not null,
  nombre     text not null,
  -- false = sus productos no entran al conteo fisico. Decision del owner
  -- (23-09-2026): 01 DIRECTO (servicios, un producto de prueba, compras
  -- puntuales) y 17 ACTIVOS SUDEMATIN (envases de Sudematin, que se controlan
  -- en el parque de cilindros de Sudematin).
  se_cuenta  boolean not null default true,
  primary key (empresa_id, codigo)
);
-- Por si la tabla ya existia de una corrida anterior sin esta columna.
alter table public.departamentos add column if not exists se_cuenta boolean not null default true;

alter table public.departamentos enable row level security;
drop policy if exists departamentos_leer on public.departamentos;
create policy departamentos_leer on public.departamentos
  for select to authenticated using (public.puede_empresa(empresa_id));
grant select on public.departamentos to authenticated;

alter table public.productos add column if not exists departamento text;
alter table public.productos drop constraint if exists productos_departamento_fk;
alter table public.productos add constraint productos_departamento_fk
  foreign key (empresa_id, departamento) references public.departamentos (empresa_id, codigo);
create index if not exists productos_departamento_idx on public.productos (empresa_id, departamento);

-- productos tiene permisos POR COLUMNA (05-correcciones: el costo queda fuera).
-- Una columna nueva no hereda el permiso: sin esta linea, pedir `departamento`
-- falla para todo usuario que no sea el servicio.
grant select (departamento) on public.productos to authenticated;

-- Productos que no son mercancia fisica y no se cuentan aunque su departamento
-- si. Un producto entra al conteo solo si EL y SU departamento se cuentan.
alter table public.productos add column if not exists se_cuenta boolean not null default true;
grant select (se_cuenta) on public.productos to authenticated;

